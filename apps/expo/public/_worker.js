/**
 * Cloudflare Pages "advanced mode" Worker for tophunt.in (Expo web SPA).
 *
 * Why this exists
 * ---------------
 * The web app is a client-side rendered Expo (React Native Web) SPA
 * (`app.json` -> web.output = "single"). Crawlers that fetch a blog URL get a
 * near-empty HTML shell with a generic <title> and no per-page meta — which is
 * fatal for Google ranking. This Worker runs at the edge in front of the static
 * assets and, for blog/permalink URLs, rewrites the shell's <head> with the
 * post's real SEO tags (title, description, canonical, Open Graph, Twitter,
 * JSON-LD Article) plus a <noscript> content block for non-JS crawlers.
 *
 * It also serves:
 *   - /robots.txt   (points at the sitemap, allows crawling)
 *   - /sitemap.xml  (all published posts + key routes, built from the API)
 *
 * Deployment: this file lives in `public/`, so `expo export` copies it to
 * `dist/_worker.js` by itself and Cloudflare Pages switches into advanced mode.
 * That is deliberate. It previously lived in `seo/` and was copied by a separate
 * post-build script, which both the Pages build command and CI forgot to run — so
 * production served a bare SPA shell to every crawler and nothing failed.
 * `scripts/verify-web-build.mjs` now asserts it made it into the output.
 *
 * In advanced mode ALL requests hit this Worker; static files and the SPA
 * fallback are served via `env.ASSETS`.
 *
 * Config (optional Pages env vars — the defaults below are the production
 * values, so a Pages project with neither var set is already correct):
 *   - SEO_API_BASE     Worker API base (default: https://api.tophunt.in)
 *   - SEO_SITE_ORIGIN  Public origin  (default: https://tophunt.in)
 *
 * Override them on a staging/preview Pages project so its sitemap and canonical
 * tags do not advertise the production origin.
 */

const DEFAULT_API_BASE = 'https://api.tophunt.in';
const DEFAULT_SITE_ORIGIN = 'https://tophunt.in';
const SITE_NAME = 'TopHunt';
const DEFAULT_DESCRIPTION =
  'TopHunt — contests, quizzes, giveaways and the latest offers, answers and updates.';

// ---------------------------------------------------------------------------
// Security headers — set HERE, not only in public/_headers.
//
// `_headers` is applied by Pages to STATIC ASSET responses. This project runs in
// advanced mode, where every request is handled by this Worker and the HTML
// document is a Response this file constructs (`fetchShell`, then HTMLRewriter).
// Cloudflare does not apply `_headers` to responses generated by a Function, so
// the entire policy in `public/_headers` — CSP, HSTS, framing — was silently
// absent from the app's documents, which is precisely where a CSP does anything.
// Nothing reports this: the file exists, the deploy succeeds, and
// `curl -I https://tophunt.in/` simply has no CSP on it.
//
// `public/_headers` is kept for the static assets it does cover. The CSP string
// below and the one in that file must stay identical; scripts/verify-web-build.mjs
// fails the build if they drift.
//
// connect-src notes (the list that the domain cutover actually changes):
//  - `wss://api.tophunt.in` is required as well as `https://`. Realtime push
//    (src/services/realtime.ts) builds its socket url by swapping the scheme on
//    the API base, and CSP matches per-scheme: the https entry does not cover it.
//  - `https://media.tophunt.in` and the legacy `<worker>/media` host are here
//    because media is FETCHED, not just displayed: share/download and the web VS
//    card capture call fetch() on an image url, which connect-src governs.
//  - Hosts are pinned exactly instead of `https://*.workers.dev`, which had
//    authorised every Cloudflare customer's Worker as a destination for a page
//    that handles logins and wallet balances.
// ---------------------------------------------------------------------------
// Exported so scripts/verify-web-build.mjs can compare it against public/_headers
// and fail the build if the two policies drift. The Workers runtime only ever
// invokes the default export; a named string export is inert there.
export const CONTENT_SECURITY_POLICY =
  "default-src 'self'; " +
  // static.cloudflareinsights.com is Cloudflare Web Analytics. Pages INJECTS its
  // beacon into every HTML response when the feature is on for the project, so
  // it is not optional from the app's side: leaving it out produced a CSP
  // violation on every single page load.
  "script-src 'self' 'unsafe-inline' https://checkout.razorpay.com https://*.gstatic.com https://*.googleapis.com https://static.cloudflareinsights.com; " +
  "style-src 'self' 'unsafe-inline'; " +
  "img-src 'self' data: blob: https:; " +
  "media-src 'self' blob: https:; " +
  "font-src 'self' data:; " +
  "connect-src 'self' blob: https://api.tophunt.in wss://api.tophunt.in https://media.tophunt.in " +
  'https://tophunt-api.weadown-in.workers.dev wss://tophunt-api.weadown-in.workers.dev ' +
  'https://tophunt-api-staging.weadown-in.workers.dev wss://tophunt-api-staging.weadown-in.workers.dev ' +
  'https://*.googleapis.com https://*.firebaseio.com wss://*.firebaseio.com ' +
  'https://securetoken.googleapis.com https://identitytoolkit.googleapis.com ' +
  'https://fcmregistrations.googleapis.com https://lumberjack.razorpay.com https://api.razorpay.com ' +
  // The analytics beacon POSTs its payload back to this host.
  'https://cloudflareinsights.com; ' +
  'frame-src https://api.razorpay.com https://checkout.razorpay.com https://*.firebaseapp.com; ' +
  "worker-src 'self'; " +
  "frame-ancestors 'none'; " +
  "base-uri 'self'; " +
  "object-src 'none'";

/** Applies to every response, document or asset. */
const TRANSPORT_HEADERS = {
  'strict-transport-security': 'max-age=31536000; includeSubDomains',
  'x-content-type-options': 'nosniff',
  'referrer-policy': 'strict-origin-when-cross-origin',
};

/** Document-only: a CSP or X-Frame-Options on a .js file protects nothing. */
const DOCUMENT_HEADERS = {
  'content-security-policy': CONTENT_SECURITY_POLICY,
  'x-frame-options': 'DENY',
  'permissions-policy': 'accelerometer=(), gyroscope=(), usb=()',
};

/**
 * Return `res` with the security headers applied.
 *
 * A Response from `env.ASSETS.fetch()` has immutable headers, so this always
 * rebuilds it. Body is passed through by reference — no buffering.
 */
function withSecurityHeaders(res, { document = false } = {}) {
  const headers = new Headers(res.headers);
  for (const [name, value] of Object.entries(TRANSPORT_HEADERS)) headers.set(name, value);
  if (document) {
    for (const [name, value] of Object.entries(DOCUMENT_HEADERS)) headers.set(name, value);
  }
  return new Response(res.body, { status: res.status, statusText: res.statusText, headers });
}

