/**
 * SEO audit engine.
 *
 * Produces a scored, severity-ranked report across eight SEO categories from two
 * sources ONLY: our own D1 content, and live HTTP probes of our own public site.
 *
 * ---------------------------------------------------------------------------
 * What this deliberately does NOT do
 * ---------------------------------------------------------------------------
 * Three categories cannot be measured from anything this deployment owns, and
 * each is reported as `not_configured` with the credential it needs rather than
 * given an invented number:
 *
 *  - OFF-PAGE (backlinks, referring domains, anchor text, domain authority,
 *    toxic-link detection). This requires a crawl index we do not have. There is
 *    no honest way to synthesise it, and a dashboard showing a made-up
 *    "Domain Authority: 34/100" is worse than an empty panel: someone will make
 *    a decision on it. Needs Search Console, or an Ahrefs/Moz/Semrush key.
 *  - PAGE SPEED / CORE WEB VITALS. Real Core Web Vitals are FIELD data from
 *    actual visitors. A Worker cannot measure them. Needs the PageSpeed Insights
 *    API (free key) or the CrUX API.
 *  - KEYWORD RESEARCH / SEARCH VOLUME / SEARCH INTENT scoring. Volume and
 *    competition come from a keyword provider; intent classification without
 *    query data is guesswork dressed as analysis.
 *
 * LOCAL SEO is scored only on the parts that genuinely apply to this product (an
 * India-focused *online* contest platform): language signals and organisation
 * contact data. It deliberately does NOT check for or recommend per-city landing
 * pages — see `LOCAL_NOTE`. That is not an omission, it is the same rule the
 * brief itself sets out under "avoid doorway pages".
 *
 * Every issue carries a deterministic `suggestion` where one can be derived from
 * the data (a truncated title, a description built from the excerpt). No text is
 * generated by a language model, so nothing here can hallucinate a fix.
 */
import { and, eq, sql } from "drizzle-orm";
import type { Env } from "../types";
import { getDb, schema } from "../db";

// ---------------------------------------------------------------------------
// Model
// ---------------------------------------------------------------------------

export type Severity = "critical" | "high" | "medium" | "low";

export type CategoryId =
  | "technical"
  | "onPage"
  | "programmatic"
  | "content"
  | "offPage"
  | "local"
  | "image"
  | "aiSearch";

export interface SeoIssue {
  /** Stable id, so a fix can be verified against the next run. */
  id: string;
  category: CategoryId;
  severity: Severity;
  title: string;
  /** Why it matters — the consequence, not a restatement of the title. */
  detail: string;
  /** Sample of affected urls/slugs, capped. `affectedCount` is the real total. */
  affected: string[];
  affectedCount: number;
  /** Deterministic, reviewable fix. Never model-generated. */
  suggestion?: string;
}

export interface PassedCheck {
  id: string;
  category: CategoryId;
  title: string;
}

export type CategoryStatus = "ok" | "warn" | "fail" | "not_configured";

export interface CategoryScore {
  id: CategoryId;
  label: string;
  /** null when the category cannot be measured — never a guessed number. */
  score: number | null;
  status: CategoryStatus;
  checksRun: number;
  checksPassed: number;
  /** Present when score is null: what is missing and how to enable it. */
  note?: string;
}

export interface SeoAudit {
  ranAt: number;
  durationMs: number;
  origin: string;
  /** Mean of the measurable categories only. */
  overall: number | null;
  categories: CategoryScore[];
  issues: SeoIssue[];
  passed: PassedCheck[];
  totals: Record<Severity, number>;
  /** Content counted, for context on the numbers above. */
  scope: { posts: number; publicRoutes: number; probes: number };
}

const CATEGORY_LABELS: Record<CategoryId, string> = {
  technical: "Technical SEO",
  onPage: "On-Page SEO",
  programmatic: "Programmatic SEO",
  content: "Content SEO",
  offPage: "Off-Page SEO",
  local: "Local SEO",
  image: "Image SEO",
  aiSearch: "AI Search / GEO",
};

/**
 * Score deductions per failing check.
 *
 * A category starts at 100 and loses this much per failing check. The weights are
 * ordered so that one critical failure alone cannot leave a category looking
 * healthy, while a handful of `low` findings cannot tank it either.
 */
const SEVERITY_WEIGHT: Record<Severity, number> = {
  critical: 30,
  high: 14,
  medium: 7,
  low: 2,
};

/** Sample size for issue lists. The full count is always reported separately. */
const SAMPLE = 8;

const NOT_CONFIGURED: Partial<Record<CategoryId, string>> = {
  offPage:
    "Needs an external backlink data source — Google Search Console, or an Ahrefs / Moz / Semrush API key. " +
    "Backlinks, referring domains, anchor text and domain authority cannot be observed from this deployment, " +
    "and this panel will not display an estimated figure in their place.",
};

const LOCAL_NOTE =
  "Scored on the signals that apply to a national online platform: page language and organisation contact data. " +
  "Per-city landing pages are intentionally not implemented or recommended: TopHunt has no per-city inventory, " +
  "service area or address, so city pages would be near-duplicate doorway pages — which the SEO policy for this " +
  "project explicitly rules out. LocalBusiness schema is likewise not applicable (no physical premises).";

