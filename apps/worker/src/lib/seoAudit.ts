// Collector
// ---------------------------------------------------------------------------

class Report {
  issues: SeoIssue[] = [];
  passed: PassedCheck[] = [];
  private run = new Map<CategoryId, number>();
  private ok = new Map<CategoryId, number>();

  /**
   * Record one check. `affected` empty ⇒ the check passed.
   *
   * Both outcomes are recorded, because a dashboard that only lists problems
   * cannot distinguish "healthy" from "never looked".
   */
  check(
    category: CategoryId,
    id: string,
    severity: Severity,
    title: string,
    detail: string,
    affected: string[],
    affectedCount = affected.length,
    suggestion?: string,
  ): void {
    this.run.set(category, (this.run.get(category) ?? 0) + 1);
    if (affectedCount === 0) {
      this.ok.set(category, (this.ok.get(category) ?? 0) + 1);
      this.passed.push({ id, category, title });
      return;
    }
    this.issues.push({
      id,
      category,
      severity,
      title,
      detail,
      affected: affected.slice(0, SAMPLE),
      affectedCount,
      suggestion,
    });
  }

  score(category: CategoryId): CategoryScore {
    const note = NOT_CONFIGURED[category] ?? (category === "local" ? LOCAL_NOTE : undefined);
    const checksRun = this.run.get(category) ?? 0;
    if (checksRun === 0) {
      return {
        id: category,
        label: CATEGORY_LABELS[category],
        score: null,
        status: "not_configured",
        checksRun: 0,
        checksPassed: 0,
        note: note ?? "No checks available for this category.",
      };
    }
    const deduction = this.issues
      .filter((i) => i.category === category)
      .reduce((sum, i) => sum + SEVERITY_WEIGHT[i.severity], 0);
    const score = Math.max(0, Math.min(100, 100 - deduction));
    const worst = this.issues.filter((i) => i.category === category);
    const status: CategoryStatus = worst.some((i) => i.severity === "critical")
      ? "fail"
      : score < 70
        ? "fail"
        : score < 90
          ? "warn"
          : "ok";
    return {
      id: category,
      label: CATEGORY_LABELS[category],
      score,
      status,
      checksRun,
      checksPassed: this.ok.get(category) ?? 0,
      ...(category === "local" ? { note } : {}),
    };
  }
}

