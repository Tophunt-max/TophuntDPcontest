/** Public routes the SEO Worker advertises. Kept in step with PUBLIC_ROUTES there. */
export const AUDITED_PUBLIC_ROUTES = [
  "/",
  "/home",
  "/explore",
  "/explore/leaderboard",
  "/blog",
  "/legal/privacy",
  "/legal/terms",
  "/legal/refund",
  "/legal/guidelines",
] as const;

/** A sample of screens that must never be indexable. */
const AUDITED_PRIVATE_ROUTES = ["/wallet/withdraw", "/auth/login", "/setting"] as const;

export function seoSiteOrigin(env: Env): string {
  const configured = String((env as any).SEO_SITE_ORIGIN || "").trim();
  return (configured || "https://tophunt.in").replace(/\/$/, "");
}

export async function runSeoAudit(env: Env): Promise<SeoAudit> {
  const startedAt = Date.now();
  const origin = seoSiteOrigin(env);
  const hostname = new URL(origin).hostname;
  const r = new Report();

  const db = getDb(env);
  const posts = await db
    .select({
      slug: schema.blogPosts.slug,
      title: schema.blogPosts.title,
      metaTitle: schema.blogPosts.metaTitle,
      metaDescription: schema.blogPosts.metaDescription,
      excerpt: schema.blogPosts.excerpt,
      content: schema.blogPosts.content,
      coverImageUrl: schema.blogPosts.coverImageUrl,
      canonicalUrl: schema.blogPosts.canonicalUrl,
      author: schema.blogPosts.author,
      category: schema.blogPosts.category,
      publishedAt: schema.blogPosts.publishedAt,
      updatedAt: schema.blogPosts.updatedAt,
    })
    .from(schema.blogPosts)
    .where(eq(schema.blogPosts.status, "published"))
    .all();

  // ---- live probes (bounded: this runs inside one Worker invocation) --------
  const routeProbes = await Promise.all(
    AUDITED_PUBLIC_ROUTES.map((p) => probe(origin, p)),
  );
  const privateProbes = await Promise.all(AUDITED_PRIVATE_ROUTES.map((p) => probe(origin, p)));
  const [robots, sitemap, notFound, samplePost] = await Promise.all([
    probe(origin, "/robots.txt", "text/plain"),
    probe(origin, "/sitemap.xml", "application/xml"),
    probe(origin, "/this-path-should-not-exist-seo-audit", "text/html"),
    posts.length ? probe(origin, `/blog/${posts[0].slug}`) : Promise.resolve(null as any),
  ]);
  const probeCount = routeProbes.length + privateProbes.length + 3 + (samplePost ? 1 : 0);

  runTechnical(r, { origin, robots, sitemap, notFound, routeProbes, privateProbes, posts });
  runOnPage(r, { origin, hostname, posts, routeProbes, samplePost });
  runProgrammatic(r, { posts, samplePost });
  runContent(r, { posts });
  runImage(r, { posts });
  runAiSearch(r, { posts, routeProbes, samplePost });
  runLocal(r, { routeProbes });

  // Off-page has no data source. One explicit, honest entry — no checks, no score.
  const categories: CategoryScore[] = (
    ["technical", "onPage", "programmatic", "content", "offPage", "local", "image", "aiSearch"] as CategoryId[]
  ).map((id) => r.score(id));

  const measurable = categories.filter((c) => c.score !== null).map((c) => c.score as number);
  const overall = measurable.length
    ? Math.round(measurable.reduce((a, b) => a + b, 0) / measurable.length)
    : null;

  const totals: Record<Severity, number> = { critical: 0, high: 0, medium: 0, low: 0 };
  for (const i of r.issues) totals[i.severity] += 1;

  const severityOrder: Severity[] = ["critical", "high", "medium", "low"];
  r.issues.sort(
    (a, b) =>
      severityOrder.indexOf(a.severity) - severityOrder.indexOf(b.severity) ||
      b.affectedCount - a.affectedCount,
  );

  return {
    ranAt: startedAt,
    durationMs: Date.now() - startedAt,
    origin,
    overall,
    categories,
    issues: r.issues,
    passed: r.passed,
    totals,
    scope: { posts: posts.length, publicRoutes: AUDITED_PUBLIC_ROUTES.length, probes: probeCount },
  };
}

// ---------------------------------------------------------------------------
// Category: Technical
// ---------------------------------------------------------------------------

function runTechnical(
  r: Report,
  x: {
    origin: string;
    robots: Probe;
    sitemap: Probe;
    notFound: Probe;
    routeProbes: Probe[];
    privateProbes: Probe[];
    posts: any[];
  },
): void {
  const { origin, robots, sitemap, notFound, routeProbes, privateProbes, posts } = x;

  r.check(
    "technical",
    "tech.https",
    "critical",
    "Site is served over HTTPS",
    "Search engines demote plain HTTP, and the app handles logins and payments.",
    origin.startsWith("https://") ? [] : [origin],
  );

  r.check(
    "technical",
    "tech.robots.reachable",
    "high",
    "robots.txt is reachable",
    "Without it crawlers apply their own defaults and cannot discover the sitemap.",
    robots.ok ? [] : ["/robots.txt"],
  );

  // Our robots.txt always advertises the sitemap. If the served one does not, it
  // is not ours — Cloudflare's managed robots.txt (AI crawl control) replaces the
  // whole file at the edge, and that is invisible from the codebase.
  const robotsIsOurs = robots.body.includes(`Sitemap: ${origin}/sitemap.xml`);
  r.check(
    "technical",
    "tech.robots.sitemap",
    "high",
    "robots.txt points at the sitemap",
    "The served robots.txt does not reference our sitemap, so crawlers will not find it there. " +
      "A managed robots.txt at the zone level (Cloudflare AI crawl control) overrides the app's own file.",
    robotsIsOurs ? [] : ["/robots.txt"],
    robotsIsOurs ? 0 : 1,
    robotsIsOurs
      ? undefined
      : "Disable the managed/AI-crawl robots.txt on the tophunt.in zone so the app's robots.txt is served, " +
        "then submit the sitemap in Search Console.",
  );

  const sitemapIsXml = sitemap.contentType.includes("xml");
  r.check(
    "technical",
    "tech.sitemap.xml",
    "critical",
    "sitemap.xml is served as XML",
    "An HTML response at /sitemap.xml means the SEO edge Worker is not running and no URLs are being submitted.",
    sitemapIsXml ? [] : ["/sitemap.xml"],
  );

  const sitemapUrls = (sitemap.body.match(/<url>/g) || []).length;
  const expected = posts.length + AUDITED_PUBLIC_ROUTES.length;
  // 2% tolerance: a post published between the sitemap's cache fill and this run
  // is not a defect.
  const shortfall = expected - sitemapUrls;
  r.check(
    "technical",
    "tech.sitemap.complete",
    "high",
    "sitemap.xml lists every public URL",
    `The sitemap holds ${sitemapUrls} URLs but ${expected} are expected (${posts.length} posts + ${AUDITED_PUBLIC_ROUTES.length} routes). ` +
      "Missing URLs are simply never advertised to search engines.",
    sitemapIsXml && shortfall > Math.ceil(expected * 0.02) ? [`${shortfall} URLs missing`] : [],
    sitemapIsXml && shortfall > Math.ceil(expected * 0.02) ? shortfall : 0,
  );

  r.check(
    "technical",
    "tech.sitemap.incomplete_flag",
    "medium",
    "sitemap.xml is not flagged incomplete",
    "The generator marks a sitemap it knows to be truncated. That marker is present.",
    sitemap.body.includes("INCOMPLETE") ? ["/sitemap.xml"] : [],
  );

  const noCanonical = routeProbes.filter((p) => p.ok && !canonicalOf(p.body)).map((p) => p.path);
  r.check(
    "technical",
    "tech.canonical.present",
    "high",
    "Every public route declares a canonical URL",
    "Without one, query strings and trailing-slash variants compete as separate pages.",
    noCanonical,
  );

  const wrongCanonical = routeProbes
    .filter((p) => {
      const c = canonicalOf(p.body);
      if (!c) return false;
      try {
        return new URL(c).origin !== origin;
      } catch {
        return true;
      }
    })
    .map((p) => p.path);
  r.check(
    "technical",
    "tech.canonical.origin",
    "critical",
    "Canonical URLs point at this site",
    "A canonical on another origin tells search engines to rank that site instead of this one.",
    wrongCanonical,
  );

  const indexablePrivate = privateProbes
    .filter((p) => {
      const robotsMeta = metaContent(p.body, "name", "robots") || "";
      return !robotsMeta.includes("noindex");
    })
    .map((p) => p.path);
  r.check(
    "technical",
    "tech.noindex.private",
    "critical",
    "Signed-in and transactional screens are noindex",
    "Wallet, auth and settings screens must not be indexable. An indexed withdrawal or OTP screen is a " +
      "privacy and trust problem, not just an SEO one.",
    indexablePrivate,
  );

  const notFoundRobots = metaContent(notFound.body, "name", "robots") || "";
  r.check(
    "technical",
    "tech.404.noindex",
    "medium",
    "Unknown paths are not indexable",
    "This SPA answers every path with 200, so a typo'd URL becomes an indexable duplicate of the shell " +
      "unless it is explicitly marked noindex.",
    notFoundRobots.includes("noindex") ? [] : [notFound.path],
  );

  const brokenRoutes = routeProbes.filter((p) => !p.ok).map((p) => `${p.path} → ${p.status || "network error"}`);
  r.check(
    "technical",
    "tech.routes.reachable",
    "critical",
    "Every advertised public route responds",
    "A route in the sitemap that does not respond wastes crawl budget and can be dropped from the index.",
    brokenRoutes,
  );
}

