function runProgrammatic(r: Report, x: { posts: any[]; samplePost: Probe | null }): void {
  const { posts, samplePost } = x;

  // Every post is reachable at BOTH /blog/<slug> and /<slug>. That is a
  // programmatic surface of ~4.5k pages with two URLs each, and canonical tags
  // are the only thing preventing it being duplicate content.
  r.check(
    "programmatic",
    "prog.dual_path.canonical",
    "critical",
    "Both URL shapes for a post resolve to one canonical",
    "Posts are served at /blog/<slug> and /<slug>. Without a canonical on both, that is ~2 duplicates per post.",
    samplePost && canonicalOf(samplePost.body) ? [] : ["/blog/<slug>"],
  );

  const dupSlugs = duplicates(posts.map((p) => p.slug.toLowerCase()));
  r.check(
    "programmatic",
    "prog.slug.unique",
    "critical",
    "Slugs are unique",
    "Two posts on one URL means one is unreachable and both look like duplicates.",
    dupSlugs.map(([v, n]) => `${v} ×${n}`),
    dupSlugs.length,
  );

  const thin = posts.filter((p) => wordCount(p.content || "") < 300).map((p) => `${p.slug} (${wordCount(p.content || "")} words)`);
  r.check(
    "programmatic",
    "prog.thin_content",
    "high",
    "Generated pages carry substantive content",
    "At scale, short near-identical pages are treated as thin/doorway content and can suppress the whole " +
      "section rather than just those pages.",
    thin,
    thin.length,
    "Expand or consolidate these. Merging several thin posts into one strong guide usually ranks better than " +
      "keeping them apart.",
  );

  const noCategory = posts.filter((p) => !(p.category || "").trim()).map((p) => p.slug);
  r.check(
    "programmatic",
    "prog.topic_cluster",
    "medium",
    "Posts are grouped into topic clusters",
    "Uncategorised posts cannot be linked into a hub-and-spoke cluster, which is how a large archive earns " +
      "topical authority instead of competing with itself.",
    noCategory,
  );
}

