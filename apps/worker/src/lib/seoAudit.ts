function runImage(r: Report, x: { posts: any[] }): void {
  const { posts } = x;

  let missingAltTotal = 0;
  const postsMissingAlt: string[] = [];
  for (const p of posts) {
    const n = imagesMissingAlt(p.content || "");
    if (n > 0) {
      missingAltTotal += n;
      postsMissingAlt.push(`${p.slug} (${n} image${n === 1 ? "" : "s"})`);
    }
  }
  r.check(
    "image",
    "image.alt.missing",
    "high",
    "Every in-content image has ALT text",
    `${missingAltTotal} images across ${postsMissingAlt.length} posts have no ALT text. ALT is both an ` +
      "accessibility requirement and the only way an image can be understood by a crawler.",
    postsMissingAlt,
    postsMissingAlt.length,
    "ALT should describe what the image shows. For imported posts the surrounding heading is usually a good " +
      "starting point — but it must be reviewed, not bulk-filled with the post title, which is worse than empty.",
  );

  const noCover = posts.filter((p) => !(p.coverImageUrl || "").trim()).map((p) => p.slug);
  r.check(
    "image",
    "image.cover.missing",
    "medium",
    "Posts have a cover image",
    "The cover doubles as the og:image, so a post without one unfurls as a text-only link preview.",
    noCover,
  );

  const LEGACY_HOST = "tophunt-api.weadown-in.workers.dev";
  const legacy = posts
    .filter((p) => (p.coverImageUrl || "").includes(LEGACY_HOST) || (p.content || "").includes(LEGACY_HOST))
    .map((p) => p.slug);
  r.check(
    "image",
    "image.legacy_host",
    "low",
    "Stored image urls are on the media domain",
    "These posts still STORE the old Worker-proxied media host. Delivery is no longer affected — " +
      "routes/read.ts canonicalises cover and in-content urls onto the media domain on the way out, " +
      "so they are CDN-served and optimised — which is why this is low rather than medium. What " +
      "remains is data hygiene: the rewrite is per-response work, anything reading these columns " +
      "directly (exports, admin tools, D1 queries) still sees the old host, and the rewrite cannot " +
      "be retired until the stored values are canonical.",
    legacy,
    legacy.length,
    "Run apps/worker/scripts/media-domain-backfill.sql (PRODUCTION_DOMAINS.md §5).",
  );

  const rasterOnly = posts
    .filter((p) => /\.(jpe?g|png)(\?|$)/i.test(p.coverImageUrl || ""))
    .map((p) => p.slug);
  r.check(
    "image",
    "image.modern_format",
    "low",
    "Cover images can be served as WebP/AVIF",
    "JPEG/PNG originals are fine as sources, but they are only converted on the fly once Cloudflare " +
      "Transformations is enabled for the media zone.",
    rasterOnly,
    rasterOnly.length,
    'Enable Transformations on the tophunt.in zone and set MEDIA_TRANSFORMATIONS = "true" — ' +
      "lib/media.ts then emits format=auto variants with no client change.",
  );
}

