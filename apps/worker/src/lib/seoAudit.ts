const stripTags = (html: string) =>
  String(html || "")
    .replace(/<script[\s\S]*?<\/script>/gi, " ")
    .replace(/<style[\s\S]*?<\/style>/gi, " ")
    .replace(/<[^>]+>/g, " ")
    .replace(/\s+/g, " ")
    .trim();

const wordCount = (html: string) => (stripTags(html).match(/\S+/g) || []).length;

/** `<img>` tags with no non-empty alt attribute. */
function imagesMissingAlt(html: string): number {
  const imgs = String(html || "").match(/<img\b[^>]*>/gi) || [];
  return imgs.filter((tag) => {
    const alt = tag.match(/\balt\s*=\s*("([^"]*)"|'([^']*)')/i);
    return !alt || !(alt[2] || alt[3] || "").trim();
  }).length;
}

/** Anything that points back at this site — the internal-link signal. */
function internalLinkCount(html: string, hostname: string): number {
  const hrefs = [...String(html || "").matchAll(/<a\b[^>]*href\s*=\s*"([^"]+)"/gi)].map((m) => m[1]);
  return hrefs.filter((h) => h.startsWith("/") || h.includes(hostname)).length;
}

const headingLevels = (html: string) =>
  [...String(html || "").matchAll(/<h([1-6])\b/gi)].map((m) => Number(m[1]));

/** Does the post read like a Q&A? Only then is FAQPage schema honest. */
function looksLikeFaq(html: string): boolean {
  const text = stripTags(html);
  const questionHeadings = [...String(html || "").matchAll(/<h[2-4]\b[^>]*>([\s\S]*?)<\/h[2-4]>/gi)]
    .map((m) => stripTags(m[1]))
    .filter((h) => /\?$/.test(h.trim()) || /^(what|how|why|when|where|which|who|is|are|can|does|do)\b/i.test(h.trim()));
  return questionHeadings.length >= 2 || (text.match(/\?/g) || []).length >= 4;
}

const isKebabSlug = (slug: string) => /^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(slug);

// ---------------------------------------------------------------------------
// Live probes of our own public site
// ---------------------------------------------------------------------------

interface Probe {
  path: string;
  status: number;
  contentType: string;
  body: string;
  ok: boolean;
}

/**
 * Fetch one of our own pages.
 *
 * `Accept: text/html` matters: the SEO Worker only rewrites the document for HTML
 * navigations, so a probe without it measures the raw shell and every on-page
 * check would report a false failure.
 */
async function probe(origin: string, path: string, accept = "text/html"): Promise<Probe> {
  try {
    const res = await fetch(`${origin}${path}`, {
      headers: { accept, "user-agent": "TopHuntSeoAudit/1.0" },
      redirect: "follow",
    });
    const body = await res.text();
    return {
      path,
      status: res.status,
      contentType: res.headers.get("content-type") || "",
      body,
      ok: res.ok,
    };
  } catch (e) {
    return { path, status: 0, contentType: "", body: "", ok: false };
  }
}

const metaContent = (html: string, attr: "name" | "property", key: string): string | null => {
  const re = new RegExp(`<meta[^>]*${attr}=["']${key}["'][^>]*content=["']([^"']*)["']`, "i");
  const alt = new RegExp(`<meta[^>]*content=["']([^"']*)["'][^>]*${attr}=["']${key}["']`, "i");
  return (html.match(re) || html.match(alt) || [])[1] ?? null;
};

const titleOf = (html: string) => (html.match(/<title>([^<]*)<\/title>/i) || [])[1] ?? null;
const canonicalOf = (html: string) =>
  (html.match(/<link[^>]*rel=["']canonical["'][^>]*href=["']([^"']+)["']/i) || [])[1] ?? null;
const hasJsonLdType = (html: string, type: string) =>
  new RegExp(`"@type"\\s*:\\s*"${type}"`).test(html);

