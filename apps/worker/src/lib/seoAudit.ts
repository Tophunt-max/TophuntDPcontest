function runContent(r: Report, x: { posts: any[] }): void {
  const { posts } = x;

  const veryThin = posts.filter((p) => wordCount(p.content || "") < 150).map((p) => p.slug);
  r.check(
    "content",
    "content.very_thin",
    "high",
    "No near-empty published posts",
    "Under ~150 words there is rarely enough to satisfy any query; these dilute the archive's quality signal.",
    veryThin,
  );

  const noExcerpt = posts.filter((p) => !(p.excerpt || "").trim()).map((p) => p.slug);
  r.check("content", "content.excerpt", "low", "Posts have an excerpt", "Used for listings, previews and as a description fallback.", noExcerpt);

  const TWO_YEARS = 730 * 24 * 60 * 60 * 1000;
  const stale = posts
    .filter((p) => {
      const ts = Number(p.updatedAt || p.publishedAt || 0);
      return ts > 0 && Date.now() - ts > TWO_YEARS;
    })
    .map((p) => p.slug);
  r.check(
    "content",
    "content.freshness",
    "medium",
    "Content has been reviewed recently",
    "Posts untouched for over two years — quiz answers and offer guides especially — go stale, and stale " +
      "pages lose rankings and erode trust when the information is wrong.",
    stale,
    stale.length,
    "Review the highest-traffic stale posts first; update or unpublish the ones that no longer apply.",
  );

  const noAuthor = posts.filter((p) => !(p.author || "").trim()).map((p) => p.slug);
  r.check(
    "content",
    "content.author",
    "medium",
    "Posts declare an author",
    "Authorship is a documented E-E-A-T signal and feeds Article schema.",
    noAuthor,
  );

  const noFaq = posts.filter((p) => !looksLikeFaq(p.content || "")).map((p) => p.slug);
  r.check(
    "content",
    "content.qa_sections",
    "low",
    "Posts include question-and-answer sections",
    "Q&A structure is what answer engines and AI search extract and cite. This is an opportunity count, not a defect.",
    noFaq,
    noFaq.length,
    "Add a short FAQ to the posts that already attract question queries; FAQPage schema then becomes eligible.",
  );
}

