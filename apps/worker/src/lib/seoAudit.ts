function runOnPage(
  r: Report,
  x: { origin: string; hostname: string; posts: any[]; routeProbes: Probe[]; samplePost: Probe | null },
): void {
  const { hostname, posts, routeProbes, samplePost } = x;

  // --- rendered routes ---
  const missingTitle = routeProbes.filter((p) => p.ok && !titleOf(p.body)).map((p) => p.path);
  r.check("onPage", "onpage.route.title", "critical", "Every public route has a <title>", "A page with no title cannot rank for anything.", missingTitle);

  const missingDesc = routeProbes.filter((p) => p.ok && !metaContent(p.body, "name", "description")).map((p) => p.path);
  r.check(
    "onPage",
    "onpage.route.description",
    "high",
    "Every public route has a meta description",
    "Without one the search snippet is scraped from arbitrary page text, and click-through suffers.",
    missingDesc,
  );

  const missingOg = routeProbes
    .filter((p) => p.ok && !metaContent(p.body, "property", "og:title"))
    .map((p) => p.path);
  r.check(
    "onPage",
    "onpage.route.og",
    "medium",
    "Every public route has Open Graph tags",
    "WhatsApp, Facebook and Telegram do not execute JavaScript; without server-rendered OG tags a shared " +
      "link unfurls as a bare URL.",
    missingOg,
  );

  const missingTwitter = routeProbes
    .filter((p) => p.ok && !metaContent(p.body, "name", "twitter:card"))
    .map((p) => p.path);
  r.check("onPage", "onpage.route.twitter", "low", "Every public route has a Twitter card", "Controls how the link renders on X.", missingTwitter);

  // --- stored post metadata ---
  const longTitles = posts
    .filter((p) => (p.metaTitle || p.title || "").length > 65)
    .map((p) => `${p.slug} (${(p.metaTitle || p.title).length} chars)`);
  r.check(
    "onPage",
    "onpage.post.title_length",
    "low",
    "Post titles fit a search result",
    "Titles beyond ~65 characters are truncated with an ellipsis in Google, hiding the end of the headline.",
    longTitles,
    longTitles.length,
    "Set a shorter `metaTitle` on these posts; the on-page <h1> can stay long.",
  );

  const shortTitles = posts.filter((p) => (p.metaTitle || p.title || "").trim().length < 15).map((p) => p.slug);
  r.check("onPage", "onpage.post.title_too_short", "medium", "Post titles are descriptive", "A very short title carries little keyword signal.", shortTitles);

  const noDescription = posts.filter((p) => !(p.metaDescription || p.excerpt || "").trim()).map((p) => p.slug);
  r.check(
    "onPage",
    "onpage.post.description",
    "high",
    "Every post has a description",
    "These posts fall back to the first words of the body as their snippet, which usually reads badly.",
    noDescription,
    noDescription.length,
    "Derive one from the opening paragraph: the audit engine can suggest per-post text, and the blog editor " +
      "accepts `metaDescription` directly.",
  );

  const badDescLength = posts
    .filter((p) => {
      const d = (p.metaDescription || p.excerpt || "").trim();
      return d.length > 0 && (d.length < 70 || d.length > 165);
    })
    .map((p) => `${p.slug} (${(p.metaDescription || p.excerpt).trim().length} chars)`);
  r.check(
    "onPage",
    "onpage.post.description_length",
    "low",
    "Descriptions are a usable length",
    "Under ~70 characters wastes the snippet; over ~165 is truncated.",
    badDescLength,
  );

  const dupTitles = duplicates(posts.map((p) => (p.metaTitle || p.title || "").trim().toLowerCase()));
  r.check(
    "onPage",
    "onpage.duplicate.title",
    "high",
    "Post titles are unique",
    "Identical titles make pages compete with each other for the same query, and look auto-generated.",
    dupTitles.map(([v, n]) => `"${v.slice(0, 60)}" ×${n}`),
    dupTitles.length,
  );

  const dupDescriptions = duplicates(
    posts.map((p) => (p.metaDescription || p.excerpt || "").trim().toLowerCase()).filter((d) => d.length > 0),
  );
  r.check(
    "onPage",
    "onpage.duplicate.description",
    "medium",
    "Post descriptions are unique",
    "Duplicated descriptions are a thin-content signal.",
    dupDescriptions.map(([v, n]) => `"${v.slice(0, 60)}" ×${n}`),
    dupDescriptions.length,
  );

  const badSlugs = posts.filter((p) => !isKebabSlug(p.slug)).map((p) => p.slug);
  r.check(
    "onPage",
    "onpage.slug.format",
    "low",
    "Slugs are lowercase and hyphenated",
    "Mixed case and underscores produce inconsistent, less readable URLs.",
    badSlugs,
  );

  const longSlugs = posts.filter((p) => p.slug.length > 75).map((p) => `${p.slug.slice(0, 50)}… (${p.slug.length})`);
  r.check("onPage", "onpage.slug.length", "low", "Slugs are a reasonable length", "Very long URLs are truncated in results and are harder to share.", longSlugs);

  const noH1 = posts.filter((p) => !headingLevels(p.content || "").includes(1)).map((p) => p.slug);
  // The edge Worker injects an <h1> into the noscript block, so this is about the
  // rendered article body, not the crawler's ability to find a heading at all.
  r.check(
    "onPage",
    "onpage.post.h1",
    "medium",
    "Post bodies contain an H1",
    "The article body has no top-level heading of its own, so the document outline depends entirely on the " +
      "injected one.",
    noH1,
  );

  const badOutline = posts
    .filter((p) => {
      const levels = headingLevels(p.content || "").filter((l) => l >= 2);
      const firstH3 = levels.indexOf(3);
      const firstH2 = levels.indexOf(2);
      return firstH3 !== -1 && (firstH2 === -1 || firstH3 < firstH2);
    })
    .map((p) => p.slug);
  r.check(
    "onPage",
    "onpage.post.heading_order",
    "low",
    "Heading levels are not skipped",
    "An H3 before any H2 breaks the outline assistive technology and crawlers rely on.",
    badOutline,
  );

  const noInternalLinks = posts.filter((p) => internalLinkCount(p.content || "", hostname) === 0).map((p) => p.slug);
  r.check(
    "onPage",
    "onpage.internal_links",
    "medium",
    "Posts link to other pages on the site",
    "Orphaned pages get less crawl attention and pass no authority onward. Internal linking is the cheapest " +
      "ranking lever available here.",
    noInternalLinks,
    noInternalLinks.length,
    "Add 2–3 contextual links per post to related posts in the same category.",
  );

  if (samplePost) {
    const canonical = canonicalOf(samplePost.body) || "";
    const doubled = /\/blog\/blog\//.test(canonical);
    r.check(
      "onPage",
      "onpage.post.canonical_shape",
      "critical",
      "Post canonical URLs point at a real route",
      "A canonical pointing at a path the app does not serve tells search engines the real page is a " +
        "duplicate of something that renders nothing.",
      doubled ? [canonical] : [],
    );
  }
}

