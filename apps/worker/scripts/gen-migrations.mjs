#!/usr/bin/env node
/**
 * Generates src/db/migrations.generated.ts from the .sql files in migrations/.
 *
 * The Worker applies migrations at runtime (src/db/autoMigrate.ts) but esbuild
 * needs STATIC imports to bundle the .sql text — it cannot read the folder at
 * runtime. So this codegen scans the folder and emits one static import per
 * migration, in filename order.
 *
 * Runs automatically before every build/deploy (wrangler.toml `[build]
 * command`) and before typecheck (package.json), so simply dropping a new
 * NNNN_name.sql file into migrations/ is enough — no manual list to maintain.
 */
import { readdirSync, writeFileSync, readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const __dirname = dirname(fileURLToPath(import.meta.url));
const migrationsDir = join(__dirname, "..", "migrations");
const outFile = join(__dirname, "..", "src", "db", "migrations.generated.ts");

const files = readdirSync(migrationsDir)
  .filter((f) => f.endsWith(".sql"))
  .sort(); // NNNN_ prefix => lexical sort == apply order

/** Turn a filename into a valid, unique JS identifier. */
const ident = (name) => "m_" + name.replace(/[^a-zA-Z0-9]/g, "_");

const imports = files.map((f) => `import ${ident(f)} from "../../migrations/${f}";`).join("\n");
const entries = files.map((f) => `  { name: ${JSON.stringify(f)}, sql: ${ident(f)} },`).join("\n");

const content = `// AUTO-GENERATED by scripts/gen-migrations.mjs — DO NOT EDIT.
// Regenerated on every build/deploy and typecheck. To add a migration, just
// drop a new NNNN_name.sql file into migrations/.
${imports}

export interface Migration {
  name: string;
  sql: string;
}

export const MIGRATIONS: Migration[] = [
${entries}
];
`;

// Only write when the content actually changes (avoids needless churn / rebuild loops).
let existing = "";
try {
  existing = readFileSync(outFile, "utf8");
} catch {
  /* first run */
}
if (existing !== content) {
  writeFileSync(outFile, content);
  console.log(`[gen-migrations] wrote ${files.length} migration(s) -> src/db/migrations.generated.ts`);
} else {
  console.log(`[gen-migrations] up to date (${files.length} migration(s))`);
}
